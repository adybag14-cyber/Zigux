    try std.testing.expectEqual(@as(?[]const u8, null), initialized_before.last_register_label);
    try std.testing.expectEqual(@as(?[]const u8, null), initialized_before.last_unregister_label);
    try std.testing.expectEqual(@as(?[]const u8, null), initialized_before.last_main_foo_bar_message);
    try std.testing.expectEqual(@as(?[]const u8, null), initialized_before.last_main_random_choice_message);
    try std.testing.expectEqual(@as(?usize, null), initialized_before.last_main_vararg_array_length);
    try std.testing.expectEqual(@as(?bool, null), initialized_before.last_main_vararg_array_terminator_zero);
    try std.testing.expectEqual(@as(?[]const u8, null), initialized_before.last_main_template_message);
    try std.testing.expectEqual(@as(?[]const u8, null), initialized_before.last_main_conditional_message);
    try std.testing.expectEqual(@as(?[]const u8, null), initialized_before.last_main_template_cond_message);
    try std.testing.expectEqual(@as(?[]const u8, null), initialized_before.last_main_template_print_message);
    try std.testing.expectEqual(@as(?[]const u8, null), initialized_before.last_main_relative_location_message);
    try std.testing.expectEqual(@as(?[]const u8, null), initialized_before.last_format_template);

    try module.registerFunctionThread();
    const initialized_replay = try module.emitFunctionIteration(3);
    try std.testing.expectEqual(@as(usize, 2), initialized_replay);
    try module.unregisterFunctionThread();

    const initialized_after = module.summary();
    try std.testing.expectEqual(ModuleStage.initialized, initialized_after.stage);
    try std.testing.expectEqual(@as(usize, 0), initialized_after.registration_depth);
    try std.testing.expectEqual(@as(usize, 0), initialized_after.main_iterations);
    try std.testing.expectEqual(@as(usize, 1), initialized_after.fn_iterations);
    try std.testing.expectEqual(@as(usize, 0), initialized_after.main_thread_events);
    try std.testing.expectEqual(@as(usize, 2), initialized_after.fn_thread_events);
    try std.testing.expectEqual(@as(usize, 2), initialized_after.total_events);
    try std.testing.expectEqual(@as(?usize, null), initialized_after.last_main_emitted_events);
    try std.testing.expectEqual(@as(?usize, 2), initialized_after.last_fn_emitted_events);
    try std.testing.expectEqual(@as(?usize, null), initialized_after.last_main_conditional_event_count);
    try std.testing.expectEqual(@as(usize, 1), initialized_after.init_runs);
    try std.testing.expectEqual(@as(usize, 0), initialized_after.selftest_runs);
    try std.testing.expectEqual(@as(usize, 0), initialized_after.exit_runs);
    try std.testing.expectEqual(@as(i32, -1), initialized_after.last_main_count);
    try std.testing.expectEqual(@as(i32, 3), initialized_after.last_fn_count);
    try std.testing.expect(!initialized_after.saw_vararg_payload);
    try std.testing.expect(!initialized_after.saw_rel_loc_payload);
    try std.testing.expect(!initialized_after.saw_conditional_path);
    try std.testing.expectEqualStrings("event-sample", initialized_after.main_thread_label orelse return error.ExpectedMainThreadLabel);
    try std.testing.expectEqualStrings("event-sample-fn", initialized_after.function_thread_label orelse return error.ExpectedFunctionThreadLabel);
    try std.testing.expectEqualStrings("foo_bar_reg", initialized_after.last_register_label orelse return error.ExpectedRegisterLabel);
    try std.testing.expectEqualStrings("foo_bar_unreg", initialized_after.last_unregister_label orelse return error.ExpectedUnregisterLabel);
    try std.testing.expectEqual(@as(?[]const u8, null), initialized_after.last_main_foo_bar_message);
    try std.testing.expectEqual(@as(?[]const u8, null), initialized_after.last_main_random_choice_message);
    try std.testing.expectEqual(@as(?usize, null), initialized_after.last_main_vararg_array_length);
    try std.testing.expectEqual(@as(?bool, null), initialized_after.last_main_vararg_array_terminator_zero);
    try std.testing.expectEqual(@as(?[]const u8, null), initialized_after.last_main_template_message);
    try std.testing.expectEqual(@as(?[]const u8, null), initialized_after.last_main_conditional_message);
    try std.testing.expectEqual(@as(?[]const u8, null), initialized_after.last_main_template_cond_message);
    try std.testing.expectEqual(@as(?[]const u8, null), initialized_after.last_main_template_print_message);
    try std.testing.expectEqual(@as(?[]const u8, null), initialized_after.last_main_relative_location_message);
    try std.testing.expectEqual(@as(?[]const u8, null), initialized_after.last_format_template);

    _ = try module.runSelftest();

    const selftest_before = module.summary();
    try std.testing.expectEqual(ModuleStage.selftest_complete, selftest_before.stage);
    try std.testing.expectEqual(@as(usize, 0), selftest_before.registration_depth);
    try std.testing.expectEqual(@as(usize, 1), selftest_before.main_iterations);
    try std.testing.expectEqual(@as(usize, 2), selftest_before.fn_iterations);
    try std.testing.expectEqual(@as(usize, 6), selftest_before.main_thread_events);
    try std.testing.expectEqual(@as(usize, 4), selftest_before.fn_thread_events);
    try std.testing.expectEqual(@as(usize, 10), selftest_before.total_events);
    try std.testing.expectEqual(@as(?usize, 6), selftest_before.last_main_emitted_events);
    try std.testing.expectEqual(@as(?usize, 2), selftest_before.last_fn_emitted_events);
    try std.testing.expectEqual(@as(?usize, 2), selftest_before.last_main_conditional_event_count);
    try std.testing.expectEqual(@as(usize, 1), selftest_before.init_runs);
    try std.testing.expectEqual(@as(usize, 1), selftest_before.selftest_runs);
    try std.testing.expectEqual(@as(usize, 0), selftest_before.exit_runs);
    try std.testing.expectEqual(@as(i32, 0), selftest_before.last_main_count);
    try std.testing.expectEqual(@as(i32, 1), selftest_before.last_fn_count);
    try std.testing.expect(selftest_before.saw_vararg_payload);
    try std.testing.expect(selftest_before.saw_rel_loc_payload);
    try std.testing.expect(selftest_before.saw_conditional_path);
    try std.testing.expectEqualStrings("event-sample", selftest_before.main_thread_label orelse return error.ExpectedMainThreadLabel);
    try std.testing.expectEqualStrings("event-sample-fn", selftest_before.function_thread_label orelse return error.ExpectedFunctionThreadLabel);
    try std.testing.expectEqualStrings("foo_bar_reg", selftest_before.last_register_label orelse return error.ExpectedRegisterLabel);
    try std.testing.expectEqualStrings("foo_bar_unreg", selftest_before.last_unregister_label orelse return error.ExpectedUnregisterLabel);
    try std.testing.expectEqualStrings("hello", selftest_before.last_main_foo_bar_message orelse return error.ExpectedMainPayload);
    try std.testing.expectEqualStrings("Mother Goose", selftest_before.last_main_random_choice_message orelse return error.ExpectedMainPayload);
    try std.testing.expectEqual(@as(usize, 0), selftest_before.last_main_vararg_array_length orelse return error.ExpectedMainPayload);
    try std.testing.expect(selftest_before.last_main_vararg_array_terminator_zero orelse return error.ExpectedMainPayload);
    try std.testing.expectEqualStrings("HELLO", selftest_before.last_main_template_message orelse return error.ExpectedMainPayload);
    try std.testing.expectEqualStrings("Some times print", selftest_before.last_main_conditional_message orelse return error.ExpectedMainPayload);
    try std.testing.expectEqualStrings("prints other times", selftest_before.last_main_template_cond_message orelse return error.ExpectedMainPayload);
    try std.testing.expectEqualStrings("I have to be different", selftest_before.last_main_template_print_message orelse return error.ExpectedMainPayload);
    try std.testing.expectEqualStrings("Hello __rel_loc", selftest_before.last_main_relative_location_message orelse return error.ExpectedMainPayload);
    try std.testing.expectEqualStrings("iter=%d", selftest_before.last_format_template orelse return error.ExpectedMainPayload);

    try module.registerFunctionThread();

    const selftest_registered_before_duplicate = module.summary();
    try std.testing.expectEqual(ModuleStage.selftest_complete, selftest_registered_before_duplicate.stage);
    try std.testing.expectEqual(@as(usize, 1), selftest_registered_before_duplicate.registration_depth);
    try std.testing.expectEqual(@as(usize, 1), selftest_registered_before_duplicate.selftest_runs);
    try std.testing.expectEqual(@as(usize, 0), selftest_registered_before_duplicate.exit_runs);
    try std.testing.expectEqual(@as(i32, 1), selftest_registered_before_duplicate.last_fn_count);
    try std.testing.expectEqualStrings("foo_bar_reg", selftest_registered_before_duplicate.last_register_label orelse return error.ExpectedRegisterLabel);

    try std.testing.expectError(error.FunctionThreadAlreadyRegistered, module.registerFunctionThread());

    const selftest_registered_after_duplicate = module.summary();
    try std.testing.expect(std.meta.eql(selftest_registered_before_duplicate, selftest_registered_after_duplicate));

    const selftest_replay = try module.emitFunctionIteration(11);
    try std.testing.expectEqual(@as(usize, 2), selftest_replay);
    try module.unregisterFunctionThread();

    const selftest_after = module.summary();
    try std.testing.expectEqual(ModuleStage.selftest_complete, selftest_after.stage);
    try std.testing.expectEqual(@as(usize, 0), selftest_after.registration_depth);
    try std.testing.expectEqual(@as(usize, 1), selftest_after.main_iterations);
    try std.testing.expectEqual(@as(usize, 3), selftest_after.fn_iterations);
    try std.testing.expectEqual(@as(usize, 6), selftest_after.main_thread_events);
    try std.testing.expectEqual(@as(usize, 6), selftest_after.fn_thread_events);
    try std.testing.expectEqual(@as(usize, 12), selftest_after.total_events);
    try std.testing.expectEqual(@as(?usize, 6), selftest_after.last_main_emitted_events);
    try std.testing.expectEqual(@as(?usize, 2), selftest_after.last_fn_emitted_events);
    try std.testing.expectEqual(@as(?usize, 2), selftest_after.last_main_conditional_event_count);
    try std.testing.expectEqual(@as(usize, 1), selftest_after.init_runs);
    try std.testing.expectEqual(@as(usize, 1), selftest_after.selftest_runs);
    try std.testing.expectEqual(@as(usize, 0), selftest_after.exit_runs);
    try std.testing.expectEqual(@as(i32, 0), selftest_after.last_main_count);
    try std.testing.expectEqual(@as(i32, 11), selftest_after.last_fn_count);
    try std.testing.expect(selftest_after.saw_vararg_payload);
    try std.testing.expect(selftest_after.saw_rel_loc_payload);
    try std.testing.expect(selftest_after.saw_conditional_path);
    try std.testing.expectEqualStrings("event-sample", selftest_after.main_thread_label orelse return error.ExpectedMainThreadLabel);
    try std.testing.expectEqualStrings("event-sample-fn", selftest_after.function_thread_label orelse return error.ExpectedFunctionThreadLabel);
    try std.testing.expectEqualStrings("foo_bar_reg", selftest_after.last_register_label orelse return error.ExpectedRegisterLabel);
    try std.testing.expectEqualStrings("foo_bar_unreg", selftest_after.last_unregister_label orelse return error.ExpectedUnregisterLabel);
    try std.testing.expectEqualStrings("hello", selftest_after.last_main_foo_bar_message orelse return error.ExpectedMainPayload);
    try std.testing.expectEqualStrings("Mother Goose", selftest_after.last_main_random_choice_message orelse return error.ExpectedMainPayload);
    try std.testing.expectEqual(@as(usize, 0), selftest_after.last_main_vararg_array_length orelse return error.ExpectedMainPayload);
    try std.testing.expect(selftest_after.last_main_vararg_array_terminator_zero orelse return error.ExpectedMainPayload);
    try std.testing.expectEqualStrings("HELLO", selftest_after.last_main_template_message orelse return error.ExpectedMainPayload);
    try std.testing.expectEqualStrings("Some times print", selftest_after.last_main_conditional_message orelse return error.ExpectedMainPayload);
    try std.testing.expectEqualStrings("prints other times", selftest_after.last_main_template_cond_message orelse return error.ExpectedMainPayload);
    try std.testing.expectEqualStrings("I have to be different", selftest_after.last_main_template_print_message orelse return error.ExpectedMainPayload);
    try std.testing.expectEqualStrings("Hello __rel_loc", selftest_after.last_main_relative_location_message orelse return error.ExpectedMainPayload);
    try std.testing.expectEqualStrings("iter=%d", selftest_after.last_format_template orelse return error.ExpectedMainPayload);

    const before_exit = module.summary();
    try std.testing.expectEqual(ModuleStage.selftest_complete, before_exit.stage);
    try std.testing.expectEqual(@as(usize, 0), before_exit.registration_depth);
    try std.testing.expectEqual(@as(usize, 1), before_exit.main_iterations);
    try std.testing.expectEqual(@as(usize, 3), before_exit.fn_iterations);
    try std.testing.expectEqual(@as(usize, 6), before_exit.main_thread_events);
    try std.testing.expectEqual(@as(usize, 6), before_exit.fn_thread_events);
    try std.testing.expectEqual(@as(usize, 12), before_exit.total_events);
    try std.testing.expectEqual(@as(usize, 1), before_exit.init_runs);
    try std.testing.expectEqual(@as(usize, 1), before_exit.selftest_runs);
    try std.testing.expectEqual(@as(usize, 0), before_exit.exit_runs);
    try std.testing.expectEqual(@as(?usize, 6), before_exit.last_main_emitted_events);
    try std.testing.expectEqual(@as(?usize, 2), before_exit.last_fn_emitted_events);
    try std.testing.expectEqual(@as(?usize, 2), before_exit.last_main_conditional_event_count);
    try std.testing.expectEqual(@as(i32, 0), before_exit.last_main_count);
    try std.testing.expectEqual(@as(i32, 11), before_exit.last_fn_count);
    try std.testing.expect(selftest_after.saw_vararg_payload == before_exit.saw_vararg_payload);
    try std.testing.expect(selftest_after.saw_rel_loc_payload == before_exit.saw_rel_loc_payload);
    try std.testing.expect(selftest_after.saw_conditional_path == before_exit.saw_conditional_path);
    try std.testing.expectEqualStrings("event-sample", before_exit.main_thread_label orelse return error.ExpectedMainThreadLabel);
    try std.testing.expectEqualStrings("event-sample-fn", before_exit.function_thread_label orelse return error.ExpectedFunctionThreadLabel);
    try std.testing.expectEqualStrings("hello", before_exit.last_main_foo_bar_message orelse return error.ExpectedMainPayload);
    try std.testing.expectEqualStrings("Mother Goose", before_exit.last_main_random_choice_message orelse return error.ExpectedMainPayload);
    try std.testing.expectEqual(@as(usize, 0), before_exit.last_main_vararg_array_length orelse return error.ExpectedMainPayload);
    try std.testing.expect(before_exit.last_main_vararg_array_terminator_zero orelse return error.ExpectedMainPayload);
    try std.testing.expectEqualStrings("HELLO", before_exit.last_main_template_message orelse return error.ExpectedMainPayload);
    try std.testing.expectEqualStrings("Some times print", before_exit.last_main_conditional_message orelse return error.ExpectedMainPayload);
    try std.testing.expectEqualStrings("prints other times", before_exit.last_main_template_cond_message orelse return error.ExpectedMainPayload);
    try std.testing.expectEqualStrings("I have to be different", before_exit.last_main_template_print_message orelse return error.ExpectedMainPayload);
    try std.testing.expectEqualStrings("Hello __rel_loc", before_exit.last_main_relative_location_message orelse return error.ExpectedMainPayload);
    try std.testing.expectEqualStrings("foo_bar_reg", before_exit.last_register_label orelse return error.ExpectedRegisterLabel);
    try std.testing.expectEqualStrings("foo_bar_unreg", before_exit.last_unregister_label orelse return error.ExpectedUnregisterLabel);
    try std.testing.expectEqualStrings("iter=%d", before_exit.last_format_template orelse return error.ExpectedMainPayload);

