fn addAbiDump(
    b: *std.Build,
    target: std.Build.ResolvedTarget,
    optimize: std.builtin.OptimizeMode,
) *std.Build.Step.Run {
    const abi_bindings = b.createModule(.{
        .root_source_file = b.path("../bindings/abi.zig"),
        .target = target,
        .optimize = optimize,
    });
    const root_module = b.createModule(.{
        .root_source_file = b.path("phase3_abi_dump_current.zig"),
        .target = target,
        .optimize = optimize,
    });
    root_module.addImport("abi_bindings", abi_bindings);

    const exe = b.addExecutable(.{
        .name = "phase3-abi-dump",
        .root_module = root_module,
    });
    return b.addRunArtifact(exe);
}

pub fn build(b: *std.Build) void {
    const target = b.standardTargetOptions(.{});
    const optimize = b.standardOptimizeOption(.{});

    const abi_core = addAbiCorePacket(b, target, optimize);
    const export_shim = addExportShim(b, target, optimize);
    const export_uapi_layout = addExportUapiLayout(b, target, optimize);
    const abi_dump = addAbiDump(b, target, optimize);

    const route = b.step(
        "phase3-abi-export-dump",
        "Run the Phase 3 ABI export packet bundle plus ABI dump from zigux/tests",
    );
    route.dependOn(&abi_core.step);
    route.dependOn(&export_shim.step);
    route.dependOn(&export_uapi_layout.step);
    route.dependOn(&abi_dump.step);

    const test_step = b.step(
        "test",
        "Run the Phase 3 ABI export/dump standalone harness",
    );
    test_step.dependOn(route);

    b.default_step.dependOn(test_step);
}
