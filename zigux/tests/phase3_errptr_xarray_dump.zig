const std = @import("std");
const Io = std.Io;
const err_ptr = @import("err_ptr");
const xa_value = @import("xa_value");

pub fn main(init: std.process.Init) !void {
    const io = init.io;
    var stdout_buffer: [4096]u8 = undefined;
    var stdout_writer = Io.File.stdout().writer(io, &stdout_buffer);
    const writer = &stdout_writer.interface;

    const err_addr = err_ptr.fromErrno(-22);
    const err_summary = err_ptr.summarize(err_addr);
    const null_summary = err_ptr.summarize(0);
    const plain_addr: usize = 0x1000;
    const plain_summary = xa_value.summarize(plain_addr);
    const encoded_addr = xa_value.make(37);
    const encoded_summary = xa_value.summarize(encoded_addr);

    try writer.writeAll("{\"constants\":{\"max_errno\":");
    try writer.print("{d}", .{err_ptr.max_errno});
    try writer.writeAll(",\"err_flag_error\":");
    try writer.print("{d}", .{@import("abi_bindings").ERR_PTR_FLAG_ERROR});
    try writer.writeAll(",\"err_flag_null\":");
    try writer.print("{d}", .{@import("abi_bindings").ERR_PTR_FLAG_NULL});
    try writer.writeAll(",\"xa_flag_value\":");
    try writer.print("{d}", .{@import("abi_bindings").XA_VALUE_FLAG_VALUE});
    try writer.writeAll(",\"xa_flag_plain\":");
    try writer.print("{d}", .{@import("abi_bindings").XA_VALUE_FLAG_PLAIN});
    try writer.writeAll("},\"err_ptr\":{\"raw_addr\":");
    try writer.print("{d}", .{err_addr});
    try writer.writeAll(",\"is_err\":");
    try writer.writeAll(if (err_ptr.isErr(err_addr)) "true" else "false");
    try writer.writeAll(",\"errno_code\":");
    try writer.print("{d}", .{err_ptr.toErrno(err_addr)});
    try writer.writeAll(",\"summary\":{\"errno_code\":");
    try writer.print("{d}", .{err_summary.errno_code});
    try writer.writeAll(",\"flags\":");
    try writer.print("{d}", .{err_summary.flags});
    try writer.writeAll("}},\"null_ptr\":{\"is_null\":");
    try writer.writeAll(if (err_ptr.isNull(0)) "true" else "false");
    try writer.writeAll(",\"is_null_or_err\":");
    try writer.writeAll(if (err_ptr.isNullOrErr(0)) "true" else "false");
    try writer.writeAll(",\"summary\":{\"errno_code\":");
    try writer.print("{d}", .{null_summary.errno_code});
    try writer.writeAll(",\"flags\":");
    try writer.print("{d}", .{null_summary.flags});
    try writer.writeAll("}},\"xa\":{\"plain\":{\"raw_addr\":");
    try writer.print("{d}", .{plain_addr});
    try writer.writeAll(",\"is_value\":");
    try writer.writeAll(if (xa_value.isValue(plain_addr)) "true" else "false");
    try writer.writeAll(",\"summary\":{\"raw_addr\":");
    try writer.print("{d}", .{plain_summary.raw_addr});
    try writer.writeAll(",\"decoded_value\":");
    try writer.print("{d}", .{plain_summary.decoded_value});
    try writer.writeAll(",\"flags\":");
    try writer.print("{d}", .{plain_summary.flags});
    try writer.writeAll("}},\"encoded\":{\"raw_addr\":");
    try writer.print("{d}", .{encoded_addr});
    try writer.writeAll(",\"is_value\":");
    try writer.writeAll(if (xa_value.isValue(encoded_addr)) "true" else "false");
    try writer.writeAll(",\"decoded_value\":");
    try writer.print("{d}", .{xa_value.toValue(encoded_addr)});
    try writer.writeAll(",\"summary\":{\"raw_addr\":");
    try writer.print("{d}", .{encoded_summary.raw_addr});
    try writer.writeAll(",\"decoded_value\":");
    try writer.print("{d}", .{encoded_summary.decoded_value});
    try writer.writeAll(",\"flags\":");
    try writer.print("{d}", .{encoded_summary.flags});
    try writer.writeAll("}}}}\n");

    try stdout_writer.interface.flush();
}