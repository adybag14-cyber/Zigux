const std = @import("std");

pub fn build(b: *std.Build) void {
    const target = b.standardTargetOptions(.{});
    const optimize = b.standardOptimizeOption(.{});

    const ctype_module = b.createModule(.{
        .root_source_file = b.path("../../tools/lib/ctype.zig"),
        .target = target,
        .optimize = optimize,
    });

    const root_module = b.createModule(.{
        .root_source_file = b.path("phase1_ctype_highbit_transform_replay.zig"),
        .target = target,
        .optimize = optimize,
    });
    root_module.addImport("ctype", ctype_module);

    const tests = b.addTest(.{
        .name = "phase1-ctype-highbit-transform-replay-tests",
        .root_module = root_module,
    });
    const run_tests = b.addRunArtifact(tests);

    const replay_step = b.step(
        "phase1-ctype-highbit-transform-replay",
        "Run Phase 1 ctype high-bit transform replay",
    );
    replay_step.dependOn(&run_tests.step);

    const test_step = b.step("test", "Run Phase 1 ctype high-bit transform replay");
    test_step.dependOn(&run_tests.step);
}
